import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";

// Posts moved from /blog/<slug>/ to /<slug>/. Emit one explicit Cloudflare Pages rule per
// published post (each has an /og/<slug>/ page) so other /blog/* paths, such as archive
// pagination and post assets, are served normally.
const dist = path.join(process.cwd(), "dist");
const slugs = (await fs.readdir(path.join(dist, "og"), { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

if (slugs.length === 0) throw new Error("no published posts found under dist/og");

const rules = slugs.flatMap((slug) => [`/blog/${slug}/ /${slug}/ 301`, `/blog/${slug} /${slug}/ 301`]);
await fs.appendFile(path.join(dist, "_redirects"), `\n# Generated by scripts/redirects.mjs\n${rules.join("\n")}\n`);
